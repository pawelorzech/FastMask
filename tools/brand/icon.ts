// Generates the "Cookie @" launcher icon: adaptive vector layers + PNG exports.
// Run: bun tools/brand/icon.ts   (needs rsvg-convert on PATH for PNGs)
import { $ } from "bun";
const RES = new URL("../../app/src/main/res/", import.meta.url).pathname;
const OUT = new URL("./out/", import.meta.url).pathname;

// oklch -> sRGB hex
function oklch(L: number, C: number, H: number) {
  const h = (H * Math.PI) / 180, a = C * Math.cos(h), b = C * Math.sin(h);
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b, m_ = L - 0.1055613458 * a - 0.0638541728 * b, s_ = L - 0.0894841775 * a - 1.291485548 * b;
  const l = l_ ** 3, m = m_ ** 3, s = s_ ** 3;
  const lin = [4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s, -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s, -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s];
  return "#" + lin.map(c => { const v = c <= 0.0031308 ? 12.92 * c : 1.055 * Math.pow(c, 1 / 2.4) - 0.055; return Math.round(Math.min(1, Math.max(0, v)) * 255).toString(16).padStart(2, "0"); }).join("").toUpperCase();
}
export const BRAND = { bg: oklch(0.62, 0.15, 58), cookie: oklch(0.94, 0.05, 70), glyph: oklch(0.4, 0.12, 58) };

// Nine-sided Material "cookie", same math as the design prototype, centred in a 108 canvas.
const N = 72, CX = 54, R = 31.7;
const r = Array.from({ length: N }, (_, i) => 1 + 0.05 * Math.cos(9 * (i / N) * Math.PI * 2));
const mx = Math.max(...r);
const pts = r.map((v, i) => { const a = (i / N) * Math.PI * 2 - Math.PI / 2; return [CX + R * (v / mx) * Math.cos(a), CX + R * (v / mx) * Math.sin(a)]; });
const f = (n: number) => n.toFixed(2);
let cookie = `M${f(pts[0][0])},${f(pts[0][1])}`;
for (let i = 0; i < N; i++) {
  const p0 = pts[(i - 1 + N) % N], p1 = pts[i], p2 = pts[(i + 1) % N], p3 = pts[(i + 2) % N];
  cookie += `C${f(p1[0] + (p2[0] - p0[0]) / 6)},${f(p1[1] + (p2[1] - p0[1]) / 6)} ${f(p2[0] - (p3[0] - p1[0]) / 6)},${f(p2[1] - (p3[1] - p1[1]) / 6)} ${f(p2[0])},${f(p2[1])}`;
}
cookie += "Z";

// Material Symbols "alternate_email" (Apache 2.0), 24-unit box, moved to the canvas centre.
const AT = "M12,2C6.48,2 2,6.48 2,12s4.48,10 10,10h5v-2h-5c-4.34,0 -8,-3.66 -8,-8s3.66,-8 8,-8 8,3.66 8,8v1.43c0,0.79 -0.71,1.57 -1.5,1.57s-1.5,-0.78 -1.5,-1.57V12c0,-2.76 -2.24,-5 -5,-5s-5,2.24 -5,5 2.24,5 5,5c1.38,0 2.64,-0.56 3.54,-1.47 0.65,0.89 1.77,1.47 2.96,1.47 1.97,0 3.5,-1.6 3.5,-3.57V12c0,-5.52 -4.48,-10 -10,-10zM12,15c-1.66,0 -3,-1.34 -3,-3s1.34,-3 3,-3 3,1.34 3,3 -1.34,3 -3,3z";
function transform(d: string, s: number, tx: number, ty: number) {
  const toks = d.match(/[a-zA-Z]|-?\d*\.?\d+(?:e-?\d+)?/g)!;
  let out = "", cmd = "", idx = 0;
  for (const t of toks) {
    if (/[a-zA-Z]/.test(t)) { cmd = t; idx = 0; out += t; continue; }
    const v = parseFloat(t), abs = cmd === cmd.toUpperCase();
    let n: number;
    if (cmd === "V" ) n = v * s + ty;
    else if (cmd === "H") n = v * s + tx;
    else if (abs && cmd !== "Z") n = v * s + (idx % 2 === 0 ? tx : ty);
    else n = v * s;
    out += (out.endsWith(cmd) ? "" : " ") + f(n); idx++;
  }
  return out;
}
const S = 1.42, at = transform(AT, S, CX - 12 * S, CX - 12 * S);

const vec = (paths: string) => `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/brand/icon.ts. Edit the script, not this file. -->\n<vector xmlns:android="http://schemas.android.com/apk/res/android"\n    android:width="108dp"\n    android:height="108dp"\n    android:viewportWidth="108"\n    android:viewportHeight="108">\n${paths}</vector>\n`;
const p = (d: string, fill: string, evenOdd = false, stroke = 0) => `    <path\n        android:fillColor="${fill}"${stroke ? `\n        android:strokeColor="${fill}"\n        android:strokeWidth="${stroke}"\n        android:strokeLineJoin="round"` : ""}${evenOdd ? '\n        android:fillType="evenOdd"' : ""}\n        android:pathData="${d}"/>\n`;
await Bun.write(RES + "drawable/ic_launcher_background.xml", vec(p("M0,0h108v108h-108z", BRAND.bg)));
await Bun.write(RES + "drawable/ic_launcher_foreground.xml", vec(p(cookie, BRAND.cookie) + p(at, BRAND.glyph, false, 1.1)));
await Bun.write(RES + "drawable/ic_launcher_monochrome.xml", vec(p(cookie + at, "#FFFFFFFF", true)));

// SVGs for legacy mipmaps and the Play Store icon (512, full bleed; Play applies its own mask).
const svg = (size: number, round: boolean) => `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="${round ? "9 9 90 90" : "0 0 108 108"}">${round ? `<clipPath id="c"><circle cx="54" cy="54" r="45"/></clipPath><g clip-path="url(#c)">` : "<g>"}<rect width="108" height="108" fill="${BRAND.bg}"/><path d="${cookie}" fill="${BRAND.cookie}"/><path d="${at}" fill="${BRAND.glyph}" stroke="${BRAND.glyph}" stroke-width="1.1" stroke-linejoin="round"/></g></svg>`;
await $`mkdir -p ${OUT}`;
await Bun.write(OUT + "icon-square.svg", svg(512, false));
await Bun.write(OUT + "icon-round.svg", svg(512, true));
await $`rsvg-convert -w 512 -h 512 ${OUT}icon-square.svg -o ${OUT}play-icon-512-alpha.png`;
await $`magick ${OUT}play-icon-512-alpha.png -background ${BRAND.bg} -alpha remove -alpha off PNG24:${RES}../../../../marketing/play/icon-512.png`;
const dens: Record<string, number> = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
for (const [d, px] of Object.entries(dens)) {
  await $`rsvg-convert -w ${px} -h ${px} ${OUT}icon-round.svg -o ${RES}mipmap-${d}/ic_launcher_round.png`;
  await $`rsvg-convert -w ${px} -h ${px} ${OUT}icon-square.svg -o ${RES}mipmap-${d}/ic_launcher.png`;
}
console.log(BRAND, "done");
