import { argbFromHex, Hct, SchemeTonalSpot, SchemeNeutral, MaterialDynamicColors as M } from "@material/material-color-utilities";
const seeds: Record<string, [string, "tonal" | "neutral"]> = {
  AMBER: ["#A8530F", "tonal"], INK: ["#4A4438", "neutral"], SAGE: ["#4E6B35", "tonal"], PLUM: ["#7A3B5E", "tonal"], COBALT: ["#2F5382", "tonal"],
};
const roles: [string, any][] = [
  ["primary", M.primary], ["onPrimary", M.onPrimary], ["primaryContainer", M.primaryContainer], ["onPrimaryContainer", M.onPrimaryContainer], ["inversePrimary", M.inversePrimary],
  ["secondary", M.secondary], ["onSecondary", M.onSecondary], ["secondaryContainer", M.secondaryContainer], ["onSecondaryContainer", M.onSecondaryContainer],
  ["tertiary", M.tertiary], ["onTertiary", M.onTertiary], ["tertiaryContainer", M.tertiaryContainer], ["onTertiaryContainer", M.onTertiaryContainer],
  ["background", M.background], ["onBackground", M.onBackground], ["surface", M.surface], ["onSurface", M.onSurface],
  ["surfaceVariant", M.surfaceVariant], ["onSurfaceVariant", M.onSurfaceVariant], ["surfaceTint", M.surfaceTint],
  ["inverseSurface", M.inverseSurface], ["inverseOnSurface", M.inverseOnSurface],
  ["error", M.error], ["onError", M.onError], ["errorContainer", M.errorContainer], ["onErrorContainer", M.onErrorContainer],
  ["outline", M.outline], ["outlineVariant", M.outlineVariant], ["scrim", M.scrim],
  ["surfaceBright", M.surfaceBright], ["surfaceDim", M.surfaceDim], ["surfaceContainerLowest", M.surfaceContainerLowest], ["surfaceContainerLow", M.surfaceContainerLow],
  ["surfaceContainer", M.surfaceContainer], ["surfaceContainerHigh", M.surfaceContainerHigh], ["surfaceContainerHighest", M.surfaceContainerHighest],
];
const hex = (a: number) => "0xFF" + (a & 0xffffff).toString(16).padStart(6, "0").toUpperCase();
let out = `// GENERATED by material-color-utilities 0.3.0 (SchemeTonalSpot; Ink uses SchemeNeutral). Do not edit by hand.\n// Seeds: ${Object.entries(seeds).map(([k, [h]]) => k + " " + h).join(", ")}\npackage com.fastmask.ui.theme\n\nimport androidx.compose.material3.ColorScheme\nimport androidx.compose.material3.darkColorScheme\nimport androidx.compose.material3.lightColorScheme\nimport androidx.compose.ui.graphics.Color\n\n`;
for (const [name, [h, kind]] of Object.entries(seeds)) {
  for (const dark of [false, true]) {
    const hct = Hct.fromInt(argbFromHex(h));
    const s = kind === "neutral" ? new SchemeNeutral(hct, dark, 0) : new SchemeTonalSpot(hct, dark, 0);
    const fn = dark ? "darkColorScheme" : "lightColorScheme";
    out += `internal val ${name[0] + name.slice(1).toLowerCase()}${dark ? "Dark" : "Light"}: ColorScheme = ${fn}(\n` + roles.map(([k, r]) => `    ${k} = Color(${hex(r.getArgb(s))}),`).join("\n") + `\n)\n\n`;
  }
}
await Bun.write(process.argv[2], out);
console.log("written", out.split("\n").length, "lines");
